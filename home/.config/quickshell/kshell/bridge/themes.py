#!/usr/bin/env python3
"""Apply a KShell theme to the whole desktop.

    themes.py apply <id>    colour scheme, window decoration, Plasma style,
                            app style (Breeze or Kvantum blur), kitty, shell
    themes.py current       print the active theme id
    themes.py list          print the theme ids

Themes are defined in ../config/themes.json. The shell reads the active theme
from ~/.local/state/kshell/theme.json (written here) to decide on blur.
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
THEMES = HERE.parent / "config" / "themes.json"
HOME = Path.home()
STATE = HOME / ".local/state/kshell"
SCHEMES = HOME / ".local/share/color-schemes"
KVANTUM = HOME / ".config/Kvantum"
AURORAE = [HOME / ".local/share/aurorae/themes", Path("/usr/share/aurorae/themes")]
DESKTOPTHEMES = [HOME / ".local/share/plasma/desktoptheme", Path("/usr/share/plasma/desktoptheme")]

NEGATIVE, NEUTRAL, POSITIVE = (218, 68, 83), (246, 116, 0), (39, 174, 96)


def load():
    themes = json.loads(THEMES.read_text())["themes"]
    by_id = {t["id"]: t for t in themes}
    for t in themes:  # blur variants inherit their base palette
        if "base" in t:
            t.setdefault("palette", by_id[t["base"]]["palette"])
    return themes, by_id


def rgb(c, alpha=None):
    return ",".join(map(str, c)) + (f",{alpha}" if alpha is not None else "")


def hexc(c, alpha=None):
    return "#" + (f"{alpha:02x}" if alpha is not None else "") + "".join(f"{v:02x}" for v in c)


def scheme_name(t):
    # Blur themes share their base scheme: the colours are identical.
    return "KShell" + "".join(p.capitalize() for p in t.get("base", t["id"]).split("-"))


# ── KDE colour scheme ─────────────────────────────────────────────────────────

def colour_scheme(t):
    p = t["palette"]
    accent, text, inactive = p["accent"], p["text"], p["textInactive"]

    def group(bg, alt, fg=text):
        return {
            "BackgroundNormal": rgb(bg), "BackgroundAlternate": rgb(alt),
            "ForegroundNormal": rgb(fg), "ForegroundInactive": rgb(inactive),
            "ForegroundActive": rgb(accent), "ForegroundLink": rgb(accent),
            "ForegroundVisited": rgb(inactive), "ForegroundNegative": rgb(NEGATIVE),
            "ForegroundNeutral": rgb(NEUTRAL), "ForegroundPositive": rgb(POSITIVE),
            "DecorationFocus": rgb(accent), "DecorationHover": rgb(accent),
        }

    header_inactive = group(p["headerInactive"], p["windowAlt"])
    header_inactive["ForegroundNormal"] = rgb(text, 150)
    selection = group(accent, accent, (255, 255, 255))
    selection.update(DecorationFocus="255,255,255", DecorationHover="255,255,255",
                     ForegroundInactive=rgb(tuple(min(255, v + 80) for v in accent)))
    groups = {
        "Colors:Window": group(p["window"], p["windowAlt"]),
        "Colors:View": group(p["view"], p["viewAlt"]),
        "Colors:Button": group(p["button"], p["buttonAlt"]),
        "Colors:Header": group(p["header"], p["windowAlt"]),
        "Colors:Header][Inactive": header_inactive,
        "Colors:Tooltip": group(p["tooltip"], p["windowAlt"]),
        "Colors:Complementary": group(p["tooltip"], p["windowAlt"]),
        "Colors:Selection": selection,
        "ColorEffects:Disabled": {"ColorAmount": "0", "ColorEffect": "0", "ContrastAmount": "0.65",
                                  "ContrastEffect": "1", "IntensityAmount": "0.1", "IntensityEffect": "2"},
        "ColorEffects:Inactive": {"ChangeSelectionColor": "true", "Enable": "false"},
        "General": {"ColorScheme": scheme_name(t), "Name": f"KShell {t['name'].split()[-1]}",
                    "shadeSortColumn": "true"},
        "KDE": {"contrast": "4"},
        "WM": {"activeBackground": rgb(p["header"]), "activeBlend": rgb(text),
               "activeForeground": rgb(text), "inactiveBackground": rgb(p["headerInactive"]),
               "inactiveBlend": rgb(inactive), "inactiveForeground": rgb(inactive)},
    }
    return "\n".join(f"[{name}]\n" + "\n".join(f"{k}={v}" for k, v in g.items()) + "\n"
                     for name, g in groups.items())


# ── Kvantum (translucent + blurred Qt apps) ───────────────────────────────────

KVANTUM_BASE = {True: "KvFlat", False: "KvFlatLight"}  # SVG graphics we reuse


def kvantum_theme(t):
    p = t["palette"]
    name = "KShell" + "".join(x.capitalize() for x in t["id"].split("-"))
    folder = KVANTUM / name
    folder.mkdir(parents=True, exist_ok=True)
    base = Path("/usr/share/Kvantum") / KVANTUM_BASE[t["dark"]]
    svg = base / f"{base.name}.svg"
    if svg.exists():
        shutil.copyfile(svg, folder / f"{name}.svg")
    text, accent = p["text"], p["accent"]
    folder.joinpath(f"{name}.kvconfig").write_text(f"""[%General]
author=KShell (generated by themes.py)
comment=Translucent, blurred windows for the KShell {t['name']} theme
inherits={base.name}
composite=true
translucent_windows=true
blurring=true
popup_blurring=true
reduce_window_opacity={t.get('appTranslucency', 25)}
reduce_menu_opacity={max(10, t.get('appTranslucency', 25) - 10)}
menu_blur_radius=12
# let the blur show through Dolphin's file view and similar panes too
transparent_dolphin_view=true
transparent_pcmanfm_view=true
transparent_pcmanfm_sidepane=true
tooltip_blur_radius=8

[GeneralColors]
window.color={hexc(p['window'])}
base.color={hexc(p['view'])}
alt.base.color={hexc(p['viewAlt'])}
button.color={hexc(p['button'])}
light.color={hexc(p['buttonAlt'])}
mid.light.color={hexc(p['windowAlt'])}
dark.color={hexc(p['headerInactive'])}
mid.color={hexc(p['windowAlt'])}
highlight.color={hexc(accent)}
inactive.highlight.color={hexc(accent, 0x99)}
text.color={hexc(text)}
window.text.color={hexc(text)}
button.text.color={hexc(text)}
disabled.text.color={hexc(p['textInactive'])}
tooltip.text.color={hexc(text)}
highlight.text.color=#ffffff
link.color={hexc(accent)}
link.visited.color={hexc(p['textInactive'])}
progress.indicator.text.color={hexc(text)}
""")
    return name


# ── kitty ─────────────────────────────────────────────────────────────────────

ANSI_DARK = ["#1d1f21", "#cc6666", "#b5bd68", "#f0c674", "#81a2be", "#b294bb", "#8abeb7", "#c5c8c6",
             "#666666", "#d54e53", "#b9ca4a", "#e7c547", "#7aa6da", "#c397d8", "#70c0b1", "#eaeaea"]
ANSI_LIGHT = ["#2b2b2b", "#c82829", "#718c00", "#b07d00", "#4271ae", "#8959a8", "#3e999f", "#8e908c",
              "#5f5f5f", "#c82829", "#5b7a00", "#a06a00", "#3465a4", "#75507b", "#06989a", "#4d4d4c"]


def kitty_theme(t):
    p = t["palette"]
    ansi = ANSI_DARK if t["dark"] else ANSI_LIGHT
    lines = [
        f"# generated by KShell themes.py ({t['id']})",
        f"background {hexc(p['view'])}",
        f"foreground {hexc(p['text'])}",
        f"cursor {hexc(p['text'])}",
        f"selection_background {hexc(p['accent'])}",
        "selection_foreground #ffffff",
        f"active_tab_background {hexc(p['accent'])}",
        "active_tab_foreground #ffffff",
        f"inactive_tab_background {hexc(p['window'])}",
        f"inactive_tab_foreground {hexc(p['textInactive'])}",
        f"background_opacity {0.78 if t['blur'] else 1.0}",
        f"background_blur {32 if t['blur'] else 0}",
        *(f"color{i} {c}" for i, c in enumerate(ansi)),
    ]
    (STATE / "kitty-theme.conf").write_text("\n".join(lines) + "\n")
    subprocess.run(["pkill", "-USR1", "-x", "kitty"], check=False)  # reload config


# ── apply ─────────────────────────────────────────────────────────────────────

def run(*cmd):
    subprocess.run(cmd, check=False, stdout=subprocess.DEVNULL)


def first_existing(dirs, name):
    return any((d / name).is_dir() for d in dirs)


def apply(t):
    STATE.mkdir(parents=True, exist_ok=True)
    SCHEMES.mkdir(parents=True, exist_ok=True)

    # 1. colour scheme (also recolours GTK apps through Plasma's gtkconfig)
    name = scheme_name(t)
    (SCHEMES / f"{name}.colors").write_text(colour_scheme(t))
    run("plasma-apply-colorscheme", name)

    # 2. window decoration: MacVentura aurorae if installed, else Breeze
    variant = "MacVentura-Dark" if t["dark"] else "MacVentura-Light"
    if first_existing(AURORAE, variant):
        library, deco = "org.kde.kwin.aurorae.v2", f"__aurorae__svg__{variant}"
    else:
        library, deco = "org.kde.breeze", "Breeze"
    run("kwriteconfig6", "--file", "kwinrc", "--group", "org.kde.kdecoration2", "--key", "library", library)
    run("kwriteconfig6", "--file", "kwinrc", "--group", "org.kde.kdecoration2", "--key", "theme", deco)
    run("qdbus6", "org.kde.KWin", "/KWin", "reconfigure")

    # 3. Plasma style (OSDs, KRunner): "default" follows the colour scheme
    style = t.get("plasmaStyle", "default")
    if not first_existing(DESKTOPTHEMES, style):
        style = "default"
    run("plasma-apply-desktoptheme", style)

    # 4. app style: Kvantum with translucency + blur for blur themes, Breeze otherwise
    if t["blur"] and shutil.which("kvantummanager"):
        kv = kvantum_theme(t)
        run("kwriteconfig6", "--file", str(KVANTUM / "kvantum.kvconfig"), "--group", "General", "--key", "theme", kv)
        widget = "kvantum"
    else:
        widget = "Breeze"
    run("kwriteconfig6", "--file", "kdeglobals", "--group", "KDE", "--key", "widgetStyle", widget)
    # KGlobalSettings::StyleChanged → running KDE apps switch style
    run("dbus-send", "--session", "--type=signal", "/KGlobalSettings",
        "org.kde.KGlobalSettings.notifyChange", "int32:2", "int32:0")

    # 5. KWin blur strength (shared by apps, the shell and Plasma popups)
    if t["blur"]:
        run("kwriteconfig6", "--file", "kwinrc", "--group", "Effect-blur", "--key", "BlurStrength",
            str(t.get("blurStrength", 12)))
    else:
        run("kwriteconfig6", "--file", "kwinrc", "--group", "Effect-blur", "--key", "BlurStrength", "--delete")
    run("qdbus6", "org.kde.KWin", "/Effects", "org.kde.kwin.Effects.reconfigureEffect", "blur")

    # 6. kitty
    kitty_theme(t)

    # 7. shell (Appearance.qml watches this file)
    (STATE / "theme.json").write_text(json.dumps({"id": t["id"], "blur": t["blur"], "dark": t["dark"]}) + "\n")


def main():
    themes, by_id = load()
    args = sys.argv[1:]
    if args[:1] == ["apply"] and len(args) == 2 and args[1] in by_id:
        apply(by_id[args[1]])
    elif args == ["current"]:
        try:
            print(json.loads((STATE / "theme.json").read_text())["id"])
        except (OSError, ValueError, KeyError):
            print("slate")
    elif args == ["list"]:
        print("\n".join(t["id"] for t in themes))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
